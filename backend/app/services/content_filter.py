"""Фильтр недопустимого текста в пользовательском контенте.

Требование App Store 1.2: у приложения с пользовательским контентом должен быть
«method for filtering objectionable content». Фильтр — первая линия: он режет
однозначную грязь на входе; всё спорное добирает модерация по жалобам.

Сверяем начала слов, а не подстроки: иначе «ребята» ловились бы на «ебят»,
а «скипидар» — на «пидар». Плата за это — пропуск форм с приставками
(«за-», «до-» и т.п.); их разбирает модерация. Пропустить и потом удалить
безопаснее, чем молча отвергать нормальные слова.
"""

import re

from app.core.exceptions import AppError

# Только однозначные корни: у каждого не должно быть ни одного приличного слова,
# начинающегося так же. Перед добавлением нового корня — проверять по словарю.
_ROOTS = (
    "хуй", "хуе", "хуё", "хуи", "хуя",
    "пизд",
    "ебал", "ебан", "ебат", "ебин", "ебл", "ебуч", "ебар",
    "ёбан", "ёбат", "ёбн",
    "бляд", "блять", "блядс",
    "мудак", "мудач", "мудац", "мудил",
    "пидор", "пидар", "пидр",
    "гандон", "гондон",
    "шлюх",
    "дроч",
    "залуп",
    "fuck", "cunt", "faggot",
)

_WORD = re.compile(r"[а-яёa-z]+")


def is_objectionable(text: str | None) -> bool:
    if not text:
        return False
    for word in _WORD.findall(text.lower()):
        normalized = word.replace("ё", "е")
        for root in _ROOTS:
            if word.startswith(root) or normalized.startswith(root.replace("ё", "е")):
                return True
    return False


def ensure_clean(*texts: str | None) -> None:
    """Бросает 422, если хоть один текст нарушает правила."""
    if any(is_objectionable(t) for t in texts):
        raise AppError(
            "objectionable_content",
            "Текст нарушает правила сообщества. Уберите оскорбительные выражения.",
            422,
        )
